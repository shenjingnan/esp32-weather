void font8x16_draw_string(uint8_t *fb, int hor_res, int ver_res,
                          const char *str, int x, int y)
{
    while (*str) {
        unsigned char c = static_cast<unsigned char>(*str++);
        if (c < 32 || c > 126) {
            c = '?';  // 非 ASCII 字符替换为 '?'
        }
        const uint8_t *glyph = s_font8x16[c - 32];  // 16 字节点阵数据

        // 字体数据为水平行布局：glyph[row] 的 bit7..bit0 = 该行从左到右 8 个像素
        for (int row = 0; row < 16; row++) {
            int py = y - 15 + row;  // 从基线向上绘制
            if (py < 0 || py >= ver_res) continue;

            uint8_t row_data = glyph[row];
            for (int col = 0; col < 8; col++) {
                if (!(row_data & (1 << (7 - col)))) continue;  // MSB = 最左像素

                int px = x + col;
                if (px < 0) continue;
                if (px >= hor_res) break;

                // SSD1306 垂直页寻址格式
                int byte_idx = (py / 8) * hor_res + px;
                int bit_idx  = py % 8;
                fb[byte_idx] |= (1 << bit_idx);  // 设置像素为亮
            }
        }
        x += 8;  // 下一个字符的 X 偏移
    }
}

int font_draw_mixed(uint8_t *fb, int hor_res, int ver_res,
                    const char *str, int x, int y)
{
    int start_x = x;

    while (*str) {
        unsigned char c = static_cast<unsigned char>(*str);

        // 检测 UTF-8 三字节中文字符 (0xE0-0xEF)
        if (c >= 0xE0 && c <= 0xEF && str[1] != '\0' && str[2] != '\0') {
            const uint8_t *glyph = find_chinese_font(str);
            if (glyph) {
                // 16x16 中文字体渲染
                for (int row = 0; row < 16; row++) {
                    int py = y - 15 + row;
                    if (py < 0 || py >= ver_res) continue;

                    uint8_t left_byte  = glyph[row * 2];
                    uint8_t right_byte = glyph[row * 2 + 1];

                    // 左半部分 (列 0-7)
                    for (int col = 0; col < 8; col++) {
                        if (!(left_byte & (1 << (7 - col)))) continue;
                        int px = x + col;
                        if (px >= 0 && px < hor_res) {
                            int byte_idx = (py / 8) * hor_res + px;
                            int bit_idx  = py % 8;
                            fb[byte_idx] |= (1 << bit_idx);
                        }
                    }
                    // 右半部分 (列 8-15)
                    for (int col = 0; col < 8; col++) {
                        if (!(right_byte & (1 << (7 - col)))) continue;
                        int px = x + 8 + col;
                        if (px >= 0 && px < hor_res) {
                            int byte_idx = (py / 8) * hor_res + px;
                            int bit_idx  = py % 8;
                            fb[byte_idx] |= (1 << bit_idx);
                        }
                    }
                }
                x += 16;  // 中文字符宽度 16px
                str += 3; // 跳过 UTF-8 三字节
                continue;
            }
            // 未找到对应中文，降级为 '?' + 跳过 3 字节
            c = '?';
            str += 3;
        } else if (c < 32 || c > 126) {
            // 非 ASCII 控制字符/非中文多字节
            if (c >= 0x80) {
                // 无法识别的多字节字符，跳过
                str++;
                continue;
            }
            c = '?';
            str++;
        } else {
            str++;
        }

        // 8x16 ASCII 字符渲染
        const uint8_t *glyph = s_font8x16[c - 32];
        for (int row = 0; row < 16; row++) {
            int py = y - 15 + row;
            if (py < 0 || py >= ver_res) continue;

            uint8_t row_data = glyph[row];
            for (int col = 0; col < 8; col++) {
                if (!(row_data & (1 << (7 - col)))) continue;
                int px = x + col;
                if (px < 0) continue;
                if (px >= hor_res) break;

                int byte_idx = (py / 8) * hor_res + px;
                int bit_idx  = py % 8;
                fb[byte_idx] |= (1 << bit_idx);
            }
        }
        x += 8;  // ASCII 字符宽度 8px
    }

    return x - start_x;  // 返回总像素宽度
}
